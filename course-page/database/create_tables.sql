-- Table for Users
CREATE TABLE IF NOT EXISTS users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lastupdate_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    dni VARCHAR(9) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    user_password VARCHAR(255) NOT NULL,
    access_level VARCHAR(10) NOT NULL DEFAULT 'User' CHECK (access_level IN ('User', 'Admin'))
);

-- Table for Images (of courses)
CREATE TABLE IF NOT EXISTS images (
    image_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_path VARCHAR(300) NOT NULL UNIQUE
);

-- Table for Categories
CREATE TABLE IF NOT EXISTS categories (
    category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

-- Table for Courses
CREATE TABLE IF NOT EXISTS courses (
    course_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id INT,
    create_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lastupdate_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    course_name VARCHAR(300) NOT NULL,
    price DECIMAL(10,2) NOT NULL CHECK (price > 0),
    init_date DATE NOT NULL,
    course_description VARCHAR(1000),
    duration VARCHAR(100) NOT NULL,
    rating DECIMAL(3,2) DEFAULT 0 CHECK (rating >= 0 AND rating <= 5),
    FOREIGN KEY (image_id) REFERENCES images(image_id) ON DELETE SET NULL
);

-- Table for Subscriptions
CREATE TABLE IF NOT EXISTS subscriptions (
    subscription_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL,
    user_id INT NOT NULL,
    course_role VARCHAR(10) NOT NULL DEFAULT 'Student' CHECK (course_role IN ('Teacher', 'Student')),
    create_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    individual_rating DECIMAL(3,2) CHECK(individual_rating >= 0 AND individual_rating <= 5),
    comment VARCHAR(300),
    lastupdate_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (course_id) REFERENCES courses(course_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    UNIQUE (course_id, user_id)
);

-- Table for Files
CREATE TABLE IF NOT EXISTS files (
    file_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id INT NOT NULL,
    file_name VARCHAR(300) NOT NULL,
    file_path VARCHAR(255) NOT NULL,
    create_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lastupdate_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (subscription_id) REFERENCES subscriptions(subscription_id) ON DELETE CASCADE
);

-- Tabla pasarela entre cursos y categorias
CREATE TABLE IF NOT EXISTS course_categories (
    course_id INT,
    category_id INT,
    PRIMARY KEY (course_id, category_id),
    FOREIGN KEY (course_id) REFERENCES courses(course_id) ON DELETE CASCADE,
    FOREIGN KEY (category_id) REFERENCES categories(category_id) ON DELETE CASCADE
);

-- gorm v1 does not recognize the models' primary keys, so every INSERT sends the id as 0.
-- MySQL took 0 as "generate the next value"; this keeps that behavior in Postgres.
-- TG_ARGV[0] is the id column of the table.
CREATE OR REPLACE FUNCTION generate_id_when_zero()
RETURNS TRIGGER AS $$
BEGIN
    IF (to_jsonb(NEW) ->> TG_ARGV[0])::INT = 0 THEN
        NEW := jsonb_populate_record(NEW, jsonb_build_object(
            TG_ARGV[0], nextval(pg_get_serial_sequence(TG_TABLE_NAME, TG_ARGV[0]))
        ));
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER users_generate_id
BEFORE INSERT ON users
FOR EACH ROW EXECUTE FUNCTION generate_id_when_zero('user_id');

CREATE OR REPLACE TRIGGER images_generate_id
BEFORE INSERT ON images
FOR EACH ROW EXECUTE FUNCTION generate_id_when_zero('image_id');

CREATE OR REPLACE TRIGGER categories_generate_id
BEFORE INSERT ON categories
FOR EACH ROW EXECUTE FUNCTION generate_id_when_zero('category_id');

CREATE OR REPLACE TRIGGER courses_generate_id
BEFORE INSERT ON courses
FOR EACH ROW EXECUTE FUNCTION generate_id_when_zero('course_id');

CREATE OR REPLACE TRIGGER subscriptions_generate_id
BEFORE INSERT ON subscriptions
FOR EACH ROW EXECUTE FUNCTION generate_id_when_zero('subscription_id');

CREATE OR REPLACE TRIGGER files_generate_id
BEFORE INSERT ON files
FOR EACH ROW EXECUTE FUNCTION generate_id_when_zero('file_id');

-- Replaces MySQL's ON UPDATE CURRENT_TIMESTAMP: only when the row changed
-- and the UPDATE did not set lastupdate_date itself
CREATE OR REPLACE FUNCTION set_lastupdate_date()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD AND NEW.lastupdate_date IS NOT DISTINCT FROM OLD.lastupdate_date THEN
        NEW.lastupdate_date := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER users_set_lastupdate_date
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_lastupdate_date();

CREATE OR REPLACE TRIGGER courses_set_lastupdate_date
BEFORE UPDATE ON courses
FOR EACH ROW EXECUTE FUNCTION set_lastupdate_date();

CREATE OR REPLACE TRIGGER subscriptions_set_lastupdate_date
BEFORE UPDATE ON subscriptions
FOR EACH ROW EXECUTE FUNCTION set_lastupdate_date();

CREATE OR REPLACE TRIGGER files_set_lastupdate_date
BEFORE UPDATE ON files
FOR EACH ROW EXECUTE FUNCTION set_lastupdate_date();

-- Recalculates the course rating after INSERT, UPDATE or DELETE on subscriptions
CREATE OR REPLACE FUNCTION update_course_rating()
RETURNS TRIGGER AS $$
DECLARE
    target_course_id INT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_course_id := OLD.course_id;
    ELSE
        target_course_id := NEW.course_id;
    END IF;

    -- On UPDATE, only when the rating actually changed
    IF TG_OP = 'UPDATE' AND NEW.individual_rating IS NOT DISTINCT FROM OLD.individual_rating THEN
        RETURN NULL;
    END IF;

    -- Average of the course ratings (0 if no ratings)
    UPDATE courses
    SET rating = COALESCE((
        SELECT AVG(individual_rating)
        FROM subscriptions
        WHERE course_id = target_course_id
    ), 0)
    WHERE course_id = target_course_id;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER update_course_rating_after_insert
AFTER INSERT ON subscriptions
FOR EACH ROW EXECUTE FUNCTION update_course_rating();

CREATE OR REPLACE TRIGGER update_course_rating_after_update
AFTER UPDATE ON subscriptions
FOR EACH ROW EXECUTE FUNCTION update_course_rating();

CREATE OR REPLACE TRIGGER update_course_rating_after_delete
AFTER DELETE ON subscriptions
FOR EACH ROW EXECUTE FUNCTION update_course_rating();
